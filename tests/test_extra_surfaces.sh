#!/usr/bin/env bash
# tests/test_extra_surfaces.sh — EXTRA version surfaces (json / toml-package / cargo-lock) through
# ONE shared resolver (bin/rtc_version_surface.py) used by BOTH --bump-versions and version_gate:
# the roadmap_target lesson — two implementations drift. Fixture mirrors echoprism's shape
# (package.json + src-tauri/{tauri.conf.json,Cargo.toml,Cargo.lock}) with decoys planted exactly
# where a scope-blind rewrite would clobber them: an inline serde version in Cargo.toml
# [dependencies], a serde [[package]] block BEFORE the target crate in Cargo.lock, and a nested
# "bundle.version" in tauri.conf.json.
#
# Cases: resolver read (3 lines), bump writes all 3 extras byte-exactly and touches NO decoy,
# gate passes after the bump, gate fails NAMING the file when an extra is hand-split, when a
# declared file is missing, and when the crate matches no block, a TWO-VERSION crate fails the
# resolver loudly (never picks one), an absent dotted json key fails, --which-config lists the
# extras.
# Rig: tests/lib/rehearsal.sh (sourced; the same is/has/summary idiom as the sibling suites).
#
# Usage: bash tests/test_extra_surfaces.sh [--help]
set -uo pipefail
case "${1:-}" in
  -h|--help) sed -n '2,/^set /{/^set /d;s/^# \{0,1\}//;p;}' "$0"; exit 0 ;;
  "") ;;
  *) echo "test_extra_surfaces.sh: unknown argument $1" >&2; exit 2 ;;
esac
export LC_ALL=C
HERE="$(cd -P "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -P "$HERE/.." && pwd)"
. "$HERE/lib/rehearsal.sh"
RESOLVER="$ROOT/bin/rtc_version_surface.py"

SURFACES='[{"path":"src-tauri/tauri.conf.json","kind":"json","key":"version"},{"path":"src-tauri/Cargo.toml","kind":"toml-package"},{"path":"src-tauri/Cargo.lock","kind":"cargo-lock","crate":"fixture"}]'

mkfx() {  # mkfx <dir> — the echoprism-shaped fixture, surfaces at 0.1.0, decoys planted
  local d=$1
  mkdir -p "$d/src-tauri"
  printf '{\n  "name": "fixture",\n  "version": "0.1.0"\n}\n' > "$d/package.json"
  printf '# Changelog\n\n## [0.1.0] — 2026-11-13 — probe\n\nx\n' > "$d/CHANGELOG.md"
  # bundle.version is a DECOY for the json writer: a scope-blind "first version field" rewrite
  # must not touch it; the root-level "version" is the declared surface.
  cat > "$d/src-tauri/tauri.conf.json" <<'JSON'
{
  "$schema": "https://schema.tauri.app/config/2",
  "version": "0.1.0",
  "identifier": "com.fixture.app",
  "bundle": {
    "version": "9.9.9-decoy"
  }
}
JSON
  # serde's inline version is a DECOY for the toml writer: it sits in [dependencies], and a
  # writer that ignores the [package] scope rewrites it.
  cat > "$d/src-tauri/Cargo.toml" <<'TOML'
[package]
name = "fixture"
version = "0.1.0"
edition = "2021"

[dependencies]
serde = { version = "1.0", features = ["derive"] }
TOML
  # the serde [[package]] block comes FIRST: a cargo-lock writer that picks the first
  # version line (or the first block) rewrites the wrong package.
  cat > "$d/src-tauri/Cargo.lock" <<'LOCK'
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "serde"
version = "1.0.219"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "fixture"
version = "0.1.0"
dependencies = [
 "serde",
]
LOCK
  cat > "$d/rtc-ship.json" <<JSON
{
  "tag_prefix": "v",
  "default_branch": "main",
  "manifest": "package.json",
  "changelog": "CHANGELOG.md",
  "extra_version_surfaces": $SURFACES
}
JSON
}

expected_tauri() {  # the tauri.conf.json the bump must produce — byte-for-byte
  cat <<JSON
{
  "\$schema": "https://schema.tauri.app/config/2",
  "version": "$1",
  "identifier": "com.fixture.app",
  "bundle": {
    "version": "9.9.9-decoy"
  }
}
JSON
}
expected_cargo_toml() {
  cat <<TOML
[package]
name = "fixture"
version = "$1"
edition = "2021"

[dependencies]
serde = { version = "1.0", features = ["derive"] }
TOML
}
expected_cargo_lock() {
  cat <<LOCK
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "serde"
version = "1.0.219"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "fixture"
version = "$1"
dependencies = [
 "serde",
]
LOCK
}

echo "== the resolver reads every declared extra =="
D="$TMP/fx1"; mkfx "$D"
out=$(python3 "$RESOLVER" read "$D" "$SURFACES"); rc=$?
is "resolver read exits 0" "0" "$rc"
is "  three surfaces, tab-separated" \
   "src-tauri/tauri.conf.json	0.1.0
src-tauri/Cargo.toml	0.1.0
src-tauri/Cargo.lock	0.1.0" "$out"

echo "== the bump writes all three extras byte-exactly, decoys untouched =="
D="$TMP/fx2"; mkfx "$D"
bash "$ROOT/bin/rtc-ship.sh" --bump-versions "$D" 0.2.0 >"$D/bump.out" 2>&1
is "bump exits 0" "0" "$?"
cmp -s "$D/src-tauri/tauri.conf.json" <(expected_tauri 0.2.0) && r=0 || r=1
is "  tauri.conf.json byte-exact (nested bundle.version decoy intact)" "0" "$r"
cmp -s "$D/src-tauri/Cargo.toml" <(expected_cargo_toml 0.2.0) && r=0 || r=1
is "  Cargo.toml byte-exact (serde inline decoy intact)" "0" "$r"
cmp -s "$D/src-tauri/Cargo.lock" <(expected_cargo_lock 0.2.0) && r=0 || r=1
is "  Cargo.lock byte-exact (serde block untouched)" "0" "$r"
is "  manifest says 0.2.0" "1" "$(grep -c '"version": "0.2.0"' "$D/package.json")"

echo "== the gate passes after the bump, and lists the extras =="
bash "$ROOT/bin/rtc-ship.sh" --versions-only "$D" >"$D/gate.out" 2>&1
is "gate passes on a consistent tree" "0" "$?"
for f in src-tauri/tauri.conf.json src-tauri/Cargo.toml src-tauri/Cargo.lock; do
  has "  gate shows $f" "$(cat "$D/gate.out")" "$f"
done

echo "== the gate fails NAMING the file when an extra is hand-split =="
D="$TMP/fx3"; mkfx "$D"; bash "$ROOT/bin/rtc-ship.sh" --bump-versions "$D" 0.2.0 >/dev/null 2>&1
python3 - "$D/src-tauri/tauri.conf.json" <<'PY'
import re, sys
p = sys.argv[1]
s = open(p).read()
s = s.replace('"version": "0.2.0"', '"version": "0.9.0"', 1)
open(p, "w").write(s)
PY
bash "$ROOT/bin/rtc-ship.sh" --versions-only "$D" >"$D/gate.out" 2>&1
is "gate fails on a hand-split extra" "1" "$?"
has "  naming the split file" "$(cat "$D/gate.out")" "tauri.conf.json"

echo "== the gate fails when a declared file is MISSING =="
D="$TMP/fx4"; mkfx "$D"; bash "$ROOT/bin/rtc-ship.sh" --bump-versions "$D" 0.2.0 >/dev/null 2>&1
rm "$D/src-tauri/Cargo.lock"
bash "$ROOT/bin/rtc-ship.sh" --versions-only "$D" >"$D/gate.out" 2>&1
is "gate fails on a missing declared file" "1" "$?"
has "  naming the missing file" "$(cat "$D/gate.out")" "Cargo.lock"

echo "== the gate fails when the crate matches NO block =="
D="$TMP/fx5"; mkfx "$D"
python3 - "$D/rtc-ship.json" <<'PY'
import sys
p = sys.argv[1]
s = open(p).read().replace('"crate":"fixture"', '"crate":"nosuch"')
open(p, "w").write(s)
PY
bash "$ROOT/bin/rtc-ship.sh" --versions-only "$D" >"$D/gate.out" 2>&1
is "gate fails on a crate that matches no block" "1" "$?"
has "  naming the crate" "$(cat "$D/gate.out")" "nosuch"

echo "== a TWO-VERSION crate fails the resolver loudly (never picks one) =="
D="$TMP/fx6"; mkfx "$D"
python3 - "$D/src-tauri/Cargo.lock" <<'PY'
import sys
p = sys.argv[1]
s = open(p).read()
s += '\n[[package]]\nname = "fixture"\nversion = "0.0.9"\nsource = "registry"\n'
open(p, "w").write(s)
PY
python3 "$RESOLVER" read "$D" "$SURFACES" >"$D/r.out" 2>&1
is "resolver read refuses a duplicated crate" "1" "$?"
has "  naming the ambiguous crate" "$(cat "$D/r.out")" "fixture"

echo "== an absent dotted json key fails the resolver (empty extraction = failure) =="
D="$TMP/fx7"; mkfx "$D"
python3 "$RESOLVER" read "$D" '[{"path":"src-tauri/tauri.conf.json","kind":"json","key":"build.missing"}]' >"$D/r.out" 2>&1
is "resolver read fails on a missing dotted key" "1" "$?"
has "  naming the surface" "$(cat "$D/r.out")" "tauri.conf.json"

echo "== --which-config lists the extras =="
D="$TMP/fx8"; mkfx "$D"
# --which-config resolves the repo from the cwd, so the fixture must BE a repo here
git -C "$D" init -q -b main
( cd "$D" && bash "$ROOT/bin/rtc-ship.sh" --which-config ) >"$D/w.out" 2>&1
is "which-config exits 0" "0" "$?"
has "  it names the extra surface key" "$(cat "$D/w.out")" "extra_version_surfaces"
has "  it lists the Cargo.lock surface" "$(cat "$D/w.out")" "src-tauri/Cargo.lock"

echo "== an empty version argument is a LOUD failure, never an empty write (deferred minor 1) =="
D="$TMP/fx9"; mkfx "$D"
python3 "$RESOLVER" write "$D" "$SURFACES" "" >"$D/w.out" 2>&1
is "write with an empty version exits 1" "1" "$?"
is "  and the surfaces were NOT touched (still 0.1.0)" "1" "$(grep -c '0.1.0' "$D/src-tauri/Cargo.toml")"

echo "== explicit-key json write on a ONE-LINE compact file (deferred minor 2) =="
D="$TMP/fx10"; mkfx "$D"
printf '{"bundle":{"version":"9.9.9-decoy"},"version":"0.1.0"}' > "$D/src-tauri/tauri.conf.json"
python3 "$RESOLVER" write "$D" '[{"path":"src-tauri/tauri.conf.json","kind":"json","key":"version"}]' 0.2.0 >"$D/w.out" 2>&1
is "compact one-line json: write exits 0" "0" "$?"
is "  root version rewritten, nested decoy intact, rest byte-exact"    '{"bundle":{"version":"9.9.9-decoy"},"version":"0.2.0"}' "$(cat "$D/src-tauri/tauri.conf.json")"

summary
